export function translate(locale: Locale, key: I18nKey, vars?: Record<string, string | number>): string {
  let text: string = locale === "zh" ? zh[key] : en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
